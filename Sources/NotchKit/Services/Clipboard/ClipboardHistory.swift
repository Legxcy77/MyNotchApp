import Foundation

public struct ClipboardItem: Equatable, Sendable, Identifiable {
    public enum Content: Equatable, Sendable {
        case text(String)
        case image(Data)
    }

    public let id: UUID
    public var content: Content
    public var copiedAt: Date

    public init(id: UUID = UUID(), content: Content, copiedAt: Date) {
        self.id = id
        self.content = content
        self.copiedAt = copiedAt
    }

    public var previewText: String {
        switch content {
        case .text(let str):
            return str
                .replacingOccurrences(of: "\n", with: " ")
                .trimmingCharacters(in: .whitespacesAndNewlines)
        case .image(let data):
            let kb = max(1, data.count / 1024)
            return "Image · \(kb) KB"
        }
    }
}

public struct ClipboardHistory: Equatable, Sendable {
    public static let maxItems = 50
    public static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    public private(set) var items: [ClipboardItem] = []

    public init() {}

    public static func shouldIgnore(pasteboardTypes: [String]) -> Bool {
        pasteboardTypes.contains { concealedTypes.contains($0) }
    }

    public mutating func record(_ content: ClipboardItem.Content, at date: Date) {
        if case .text(let str) = content, str.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return
        }
        items.removeAll { $0.content == content }
        items.insert(ClipboardItem(content: content, copiedAt: date), at: 0)
        if items.count > Self.maxItems {
            items.removeLast(items.count - Self.maxItems)
        }
    }

    public func filtered(by query: String) -> [ClipboardItem] {
        let q = query.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !q.isEmpty else { return items }
        return items.filter { $0.previewText.localizedCaseInsensitiveContains(q) }
    }
}

