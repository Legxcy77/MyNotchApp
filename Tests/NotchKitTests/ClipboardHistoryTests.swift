import Foundation
import Testing
@testable import NotchKit

@Suite struct ClipboardHistoryTests {
    @Test func deduplicatesAndMovesLatestToFront() {
        var history = ClipboardHistory()
        let t0 = Date(timeIntervalSince1970: 100)
        let t1 = Date(timeIntervalSince1970: 200)
        let t2 = Date(timeIntervalSince1970: 300)

        history.record(.text("first"), at: t0)
        history.record(.text("second"), at: t1)
        history.record(.text("first"), at: t2)

        #expect(history.items.count == 2)
        #expect(history.items[0].content == .text("first"))
        #expect(history.items[0].copiedAt == t2)
        #expect(history.items[1].content == .text("second"))
    }

    @Test func capsAtMaxItems() {
        var history = ClipboardHistory()
        for i in 0..<(ClipboardHistory.maxItems + 10) {
            history.record(.text("item-\(i)"), at: Date(timeIntervalSince1970: Double(i)))
        }
        #expect(history.items.count == ClipboardHistory.maxItems)
        #expect(history.items.first?.content == .text("item-\(ClipboardHistory.maxItems + 9)"))
    }

    @Test func ignoresConcealedPasswordManagerTypes() {
        #expect(ClipboardHistory.shouldIgnore(pasteboardTypes: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]))
        #expect(ClipboardHistory.shouldIgnore(pasteboardTypes: ["org.nspasteboard.AutoGeneratedType"]))
        #expect(!ClipboardHistory.shouldIgnore(pasteboardTypes: ["public.utf8-plain-text"]))
    }

    @Test func filtersCaseInsensitively() {
        var history = ClipboardHistory()
        history.record(.text("Hello World"), at: .now)
        history.record(.text("swift build"), at: .now)

        #expect(history.filtered(by: "").count == 2)
        #expect(history.filtered(by: "SWIFT").count == 1)
        #expect(history.filtered(by: "missing").isEmpty)
    }
}

